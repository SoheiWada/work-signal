"""Independent Page link delivery. One POST, durable claim in the caller, GET-only confirmation.

A lost response never authorizes a resend. Existing articles are permanently
excluded by the reviewed rollout snapshot, even if their dates are changed.
"""
import json
import re
from datetime import datetime, timezone, timedelta
from urllib.parse import urlencode, urlsplit, parse_qsl

PAGE_ID = '1522891270900103'
API = 'https://graph.facebook.com/v27.0'
FIELDS = 'id,from,is_published,message,permalink_url,attachments{url,target,subattachments}'


def policy(root):
    try:
        p = json.loads((root / '.github/facebook-channel.json').read_text())
        start = datetime.fromisoformat(p['new_articles_from'].replace('Z', '+00:00'))
        ids = p['excluded_existing_ids']
        if (p.get('schema') != 'work-signal-facebook-channel-v1' or
                p.get('page_id') != PAGE_ID or p.get('graph_version') != 'v27.0' or
                start.tzinfo is None or not isinstance(ids, list) or not ids or
                any(not isinstance(x, str) or not x for x in ids) or len(set(ids)) != len(ids)):
            raise ValueError()
        activation = p.get('activated_at')
        if activation is not None:
            activated = datetime.fromisoformat(activation.replace('Z', '+00:00'))
            if activated.tzinfo is None or activated < start:
                raise ValueError()
        return p, start
    except (OSError, KeyError, TypeError, ValueError, AttributeError):
        raise RuntimeError('Facebook rollout policy missing/invalid; no Facebook write authorized') from None


def eligible(article, root, clock=None):
    p, start = policy(root)
    if article.get('id') in p['excluded_existing_ids'] or p.get('activated_at') is None:
        return False
    try:
        stamp = datetime.fromisoformat(article['published_at_time'].replace('Z', '+00:00'))
        return (stamp.tzinfo is not None and datetime.fromisoformat(p['activated_at'].replace('Z', '+00:00')) <= stamp <= (clock or datetime.now(timezone.utc))
                and stamp.astimezone(timezone(timedelta(hours=9))).date().isoformat()
                == article.get('published_at'))
    except (KeyError, TypeError, ValueError, AttributeError):
        return False


def text(article, canonical):
    title, summary = article['title'].strip(), article['summary'].strip()
    # Always build from the approved fields; never accept an arbitrary caption or tracking URL.
    body = title + '\n\n' + summary + '\n\n' + canonical
    if len(body) > 60000 or re.search(r'https?://[^\s]*[?&]utm_', body, re.I):
        raise ValueError('Facebook text too long or contains prohibited UTM parameters')
    return body


def verify_account(request, token):
    profile = request(API + '/me?fields=id,name', token=token)
    if str(profile.get('id', '')) != PAGE_ID or not profile.get('name'):
        raise RuntimeError('Facebook token must represent the approved Page (not a user or another Page)')
    return profile


def valid_id(value):
    return isinstance(value, str) and re.fullmatch(PAGE_ID + r'_[0-9]+', value) is not None


def safe_permalink(value):
    if not isinstance(value, str):
        return False
    try:
        p = urlsplit(value)
        return (p.scheme == 'https' and p.hostname in ('www.facebook.com', 'facebook.com')
                and not p.username and not p.password and p.port in (None, 443)
                and bool(p.path) and not any(k.lower().startswith('utm_') for k, _ in parse_qsl(p.query)))
    except ValueError:
        return False


def canonical_link(value, canonical):
    # fbclid is a Facebook click identifier, not a parameter generated by us.
    if not isinstance(value, str):
        return False
    try:
        p, c = urlsplit(value), urlsplit(canonical)
        return (p.scheme, p.netloc, p.path, p.fragment) == (c.scheme, c.netloc, c.path, '') and all(
            key == 'fbclid' for key, _ in parse_qsl(p.query, keep_blank_values=True))
    except ValueError:
        return False


def attachment_urls(item):
    result = []
    def visit(node, depth=0):
        if depth > 4 or not isinstance(node, dict):
            return
        if isinstance(node.get('url'), str):
            result.append(node['url'])
        target = node.get('target')
        if isinstance(target, dict) and isinstance(target.get('url'), str):
            result.append(target['url'])
        for key in ('attachments', 'subattachments'):
            collection = node.get(key)
            if isinstance(collection, dict) and isinstance(collection.get('data'), list):
                for child in collection['data']:
                    visit(child, depth + 1)
    visit(item)
    return result


def matches(article, items, canonical):
    body = text(article, canonical)
    found = []
    for item in items:
        if (valid_id(item.get('id')) and str((item.get('from') or {}).get('id', '')) == PAGE_ID
                and item.get('is_published') is True and item.get('message') == body
                and safe_permalink(item.get('permalink_url'))
                and any(canonical_link(url, canonical) for url in attachment_urls(item))):
            found.append({**item, 'permalink': item['permalink_url']})
    return found


def history(request, token):
    items, after = [], None
    for _ in range(25):
        args = {'fields': FIELDS, 'limit': 100}
        if after:
            args['after'] = after
        response = request(API + '/' + PAGE_ID + '/published_posts?' + urlencode(args), token=token)
        rows = response.get('data')
        if not isinstance(rows, list) or any(not isinstance(x, dict) or not valid_id(x.get('id')) for x in rows):
            raise RuntimeError('Invalid Facebook history; no absence inferred')
        items.extend(rows)
        paging = response.get('paging', {})
        if not isinstance(paging, dict):
            raise RuntimeError('Invalid Facebook pagination')
        if not paging.get('next'):
            return items
        next_after = (paging.get('cursors') or {}).get('after')
        if not isinstance(next_after, str) or not next_after or next_after == after or len(next_after) > 4096:
            break
        after = next_after  # Never follow a paging.next URL containing credentials.
    raise RuntimeError('Incomplete Facebook history; no absence inferred')


def existing(request, article, token, canonical):
    items = history(request, token)
    found = matches(article, items, canonical)
    linked = [item for item in items if any(canonical_link(url, canonical) for url in
              attachment_urls(item) + re.findall(r"https://[^\s]+", str(item.get('message') or '')))]
    if len(linked) != len(found):
        raise RuntimeError('Existing Facebook article link has conflicting/unverified content; manual review required')
    if len(found) > 1:
        raise RuntimeError('Multiple Facebook matches; manual review required')
    return found[0] if found else None


def publish(request, article, token, canonical, progress):
    progress('publish_requested', '')  # Caller must durably persist this before POST.
    result = request(API + '/' + PAGE_ID + '/feed', token=token, method='POST',
                     data={'message': text(article, canonical), 'link': canonical, 'published': 'true'})
    remote = result.get('id')
    if not valid_id(remote):
        raise RuntimeError('Facebook write response unconfirmed')
    progress('publish_response_received', remote)
    return remote


def verify(request, article, token, canonical, expected_id=''):
    if not expected_id:
        return existing(request, article, token, canonical)
    if not valid_id(expected_id):
        raise RuntimeError('Invalid Facebook response post identity')
    item = request(API + '/' + expected_id + '?' + urlencode({'fields': FIELDS}), token=token)
    found = matches(article, [item], canonical)
    if not found or found[0]['id'] != expected_id:
        raise RuntimeError('Facebook live post/link/body confirmation unavailable')
    return found[0]
